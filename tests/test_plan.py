"""Parsing the plan JSON, against real captured output.

Every fixture these run on was generated by a real binary. The parser's job
is to be right about output that exists, not output we imagined.
"""

from __future__ import annotations

from typing import Any

import pytest

from crosswind.core.findings import DriftKind
from crosswind.core.plan import MalformedPlan, parse_plan
from crosswind.core.redact import PLACEHOLDER

# --- the shape both binaries agree on ----------------------------------


def test_parses_terraform_drift(terraform_delete_drift: dict[str, Any]) -> None:
    summary = parse_plan(terraform_delete_drift)
    assert summary.format_version == "1.2"
    assert summary.terraform_version == "1.15.8"
    assert summary.has_drift
    assert {entry.address for entry in summary.drift} == {
        "local_file.config",
        "local_file.notes",
        "local_sensitive_file.secret",
    }


def test_parses_opentofu_drift(opentofu_delete_drift: dict[str, Any]) -> None:
    """OpenTofu's output parses identically, including the version it reports."""
    summary = parse_plan(opentofu_delete_drift)
    assert summary.format_version == "1.2"
    assert summary.terraform_version == "1.13.2"
    assert len(summary.drift) == 2


def test_clean_stack_has_no_drift_key_and_parses_as_clean(
    opentofu_clean: dict[str, Any],
) -> None:
    """The fixture genuinely has no `resource_drift` key. That must mean clean.

    This is the behaviour the design note is about: absent, not empty.
    """
    assert "resource_drift" not in opentofu_clean
    summary = parse_plan(opentofu_clean)
    assert not summary.has_drift
    assert summary.drift == ()


def test_provider_host_difference_is_normalised(
    terraform_delete_drift: dict[str, Any], opentofu_delete_drift: dict[str, Any]
) -> None:
    """`registry.terraform.io/...` and `registry.opentofu.org/...` agree here.

    Nothing keys on the provider, but it reaches the report header, and a
    reader should not have to wonder whether the registry host is meaningful.
    """
    from_tf = parse_plan(terraform_delete_drift).drift[0].provider
    from_tofu = parse_plan(opentofu_delete_drift).drift[0].provider
    assert from_tf == from_tofu == "hashicorp/local"


# --- deletion ----------------------------------------------------------


def test_deleted_resource_is_one_change_not_forty(
    terraform_delete_drift: dict[str, Any],
) -> None:
    """A vanished resource is one fact. The prior state has a dozen attributes."""
    summary = parse_plan(terraform_delete_drift)
    entry = next(e for e in summary.drift if e.address == "local_file.config")
    assert entry.kind is DriftKind.DELETED
    assert len(entry.changes) == 1
    assert entry.changes[0].path == "(resource)"
    assert (entry.changes[0].before, entry.changes[0].after) == ("present", "absent")


# --- addresses ---------------------------------------------------------


def test_count_foreach_and_module_addresses_survive_verbatim(
    terraform_module_drift: dict[str, Any],
) -> None:
    """The address is what a user greps for, so it is carried through as-is."""
    summary = parse_plan(terraform_module_drift)
    by_address = {entry.address: entry for entry in summary.drift}
    assert "local_file.counted[1]" in by_address
    assert 'local_file.keyed["alpha"]' in by_address
    assert "module.thing.local_file.inner" in by_address

    assert by_address["local_file.counted[1]"].index == 1
    assert by_address['local_file.keyed["alpha"]'].index == "alpha"
    assert by_address["module.thing.local_file.inner"].module_address == "module.thing"


# --- sensitivity -------------------------------------------------------


def test_provider_marked_sensitive_values_never_reach_a_change(
    terraform_delete_drift: dict[str, Any],
) -> None:
    """`local_sensitive_file` marks `content`; the real value is in the fixture.

    The fixture's prior state contains `db-password-ORIGINAL`. A deletion is
    reported as a single synthetic change, so the value is dropped entirely
    rather than redacted — which is the stronger outcome.
    """
    summary = parse_plan(terraform_delete_drift)
    entry = next(e for e in summary.drift if e.resource_type == "local_sensitive_file")
    rendered = repr([change.to_dict() for change in entry.changes])
    assert "db-password-ORIGINAL" not in rendered


def test_sensitive_attribute_in_a_changed_resource_is_redacted() -> None:
    """The `update` path: a marked attribute is replaced, not printed.

    Shaped exactly like the real `change` object captured in
    `terraform-1.15.8-update-change.json`, which is where the key names and
    the marker structure come from.
    """
    payload = {
        "format_version": "1.2",
        "terraform_version": "1.15.8",
        "resource_drift": [
            {
                "address": "aws_db_instance.main",
                "mode": "managed",
                "type": "aws_db_instance",
                "name": "main",
                "provider_name": "registry.terraform.io/hashicorp/aws",
                "change": {
                    "actions": ["update"],
                    "before": {"password": "hunter2-OLD", "instance_class": "db.t3.micro"},
                    "after": {"password": "hunter2-NEW", "instance_class": "db.t3.large"},
                    "before_sensitive": {"password": True},
                    "after_sensitive": {"password": True},
                },
            }
        ],
    }
    entry = parse_plan(payload).drift[0]
    changes = {change.path: change for change in entry.changes}

    assert changes["password"].before == PLACEHOLDER
    assert changes["password"].after == PLACEHOLDER
    assert changes["password"].provider_sensitive is True
    # The attribute that isn't a secret is still readable, which is the point.
    assert changes["instance_class"].before == "db.t3.micro"
    assert changes["instance_class"].after == "db.t3.large"

    serialised = repr(entry.changes)
    assert "hunter2-OLD" not in serialised
    assert "hunter2-NEW" not in serialised


def test_unchanged_attributes_are_dropped() -> None:
    """Terraform puts the whole object in `before`. Only differences are drift."""
    payload = {
        "format_version": "1.2",
        "terraform_version": "1.15.8",
        "resource_drift": [
            {
                "address": "aws_instance.web",
                "mode": "managed",
                "type": "aws_instance",
                "name": "web",
                "change": {
                    "actions": ["update"],
                    "before": {"instance_type": "t3.micro", "ami": "ami-123", "tags": None},
                    "after": {"instance_type": "t3.large", "ami": "ami-123", "tags": None},
                    "before_sensitive": {},
                    "after_sensitive": {},
                },
            }
        ],
    }
    entry = parse_plan(payload).drift[0]
    assert [change.path for change in entry.changes] == ["instance_type"]


def test_nested_paths_are_flattened_to_dotted_form() -> None:
    """A security group rule change has to be addressable attribute by attribute."""
    payload = {
        "format_version": "1.2",
        "terraform_version": "1.15.8",
        "resource_drift": [
            {
                "address": "aws_security_group.web",
                "mode": "managed",
                "type": "aws_security_group",
                "name": "web",
                "change": {
                    "actions": ["update"],
                    "before": {"ingress": [{"cidr_blocks": ["10.0.0.0/8"], "from_port": 443}]},
                    "after": {"ingress": [{"cidr_blocks": ["0.0.0.0/0"], "from_port": 443}]},
                    "before_sensitive": {},
                    "after_sensitive": {},
                },
            }
        ],
    }
    entry = parse_plan(payload).drift[0]
    assert [change.path for change in entry.changes] == ["ingress.0.cidr_blocks.0"]
    assert entry.changes[0].before == "10.0.0.0/8"
    assert entry.changes[0].after == "0.0.0.0/0"


def test_derived_checksum_attributes_are_suppressed_but_counted() -> None:
    """Six checksums restating one `content` change is noise, not six findings."""
    payload = {
        "format_version": "1.2",
        "terraform_version": "1.15.8",
        "resource_drift": [
            {
                "address": "local_file.a",
                "mode": "managed",
                "type": "local_file",
                "name": "a",
                "change": {
                    "actions": ["update"],
                    "before": {"content": "a", "content_md5": "x", "content_sha256": "y"},
                    "after": {"content": "b", "content_md5": "p", "content_sha256": "q"},
                    "before_sensitive": {},
                    "after_sensitive": {},
                },
            }
        ],
    }
    entry = parse_plan(payload).drift[0]
    assert [change.path for change in entry.changes] == ["content"]
    assert set(entry.suppressed) == {"content_md5", "content_sha256"}


def test_data_sources_are_not_reported_as_drift() -> None:
    """Data sources re-read every run by design. That is not drift."""
    payload = {
        "format_version": "1.2",
        "terraform_version": "1.15.8",
        "resource_drift": [
            {
                "address": "data.aws_ami.latest",
                "mode": "data",
                "type": "aws_ami",
                "name": "latest",
                "change": {
                    "actions": ["update"],
                    "before": {"id": "ami-1"},
                    "after": {"id": "ami-2"},
                },
            }
        ],
    }
    assert parse_plan(payload).drift == ()


# --- malformed input ---------------------------------------------------


def test_missing_format_version_is_an_error() -> None:
    """A stack we cannot parse must fail, never read as clean."""
    with pytest.raises(MalformedPlan, match="format_version"):
        parse_plan({"terraform_version": "1.15.8"})


def test_future_major_format_version_is_refused() -> None:
    with pytest.raises(MalformedPlan, match="not supported"):
        parse_plan({"format_version": "2.0", "terraform_version": "2.0.0"})


def test_resource_drift_that_is_not_a_list_is_an_error() -> None:
    with pytest.raises(MalformedPlan, match="not a list"):
        parse_plan({"format_version": "1.2", "terraform_version": "1.15.8", "resource_drift": {}})


def test_entry_without_address_is_an_error() -> None:
    with pytest.raises(MalformedPlan, match="address"):
        parse_plan(
            {
                "format_version": "1.2",
                "terraform_version": "1.15.8",
                "resource_drift": [{"mode": "managed", "change": {"actions": ["update"]}}],
            }
        )


def test_entry_without_change_is_an_error() -> None:
    with pytest.raises(MalformedPlan, match="change"):
        parse_plan(
            {
                "format_version": "1.2",
                "terraform_version": "1.15.8",
                "resource_drift": [{"address": "a.b", "mode": "managed"}],
            }
        )


def test_replacement_is_distinguished_from_deletion() -> None:
    payload = {
        "format_version": "1.2",
        "terraform_version": "1.15.8",
        "resource_drift": [
            {
                "address": "aws_instance.web",
                "mode": "managed",
                "type": "aws_instance",
                "name": "web",
                "change": {
                    "actions": ["delete", "create"],
                    "before": {"ami": "ami-1"},
                    "after": {"ami": "ami-2"},
                },
            }
        ],
    }
    assert parse_plan(payload).drift[0].kind is DriftKind.REPLACED
